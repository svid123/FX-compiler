void SSerializable::SSerializerIOContext::SaveString(const std::string &s)
{
	std::string sStr(s);

	unsigned char B=(unsigned char)sStr.length();
	sStr.resize(B);

	for (size_t n=0;n<sStr.length();++n)
	{
		sStr[n]^=g_auRNum[nRNDPos++];
		nRNDPos&=_countof(g_auRNum)-1;
	}

	
	fwrite(&B,1,1,fOut);
	fwrite(sStr.c_str(),B,1,fOut);
}

std::string SSerializable::SSerializerIOContext::LoadString()
{
	unsigned char B=pIn->get();
	std::string s;

	s.resize(B);
	if (B)
		pIn->read((char *)s.c_str(),B);

	for (size_t n=0;n<s.length();++n)
	{
		s[n]^=g_auRNum[nRNDPos++];
		nRNDPos&=_countof(g_auRNum)-1;
	}

	return s;
}








